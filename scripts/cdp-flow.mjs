import { chromium } from 'playwright-core';
const browser = await chromium.connectOverCDP('http://foodsky-test:9222');
const ctx = browser.contexts()[0] ?? await browser.newContext();
const page = await ctx.newPage();
const log = [];
const rec = (n, ok, d = '') => log.push((ok ? 'PASS ' : 'FAIL ') + n + (d ? ' — ' + d : ''));
await page.setViewportSize({ width: 1200, height: 675 });
await page.goto('http://openclaw-gateway:5180/', { waitUntil: 'load' });
await page.waitForFunction(() => typeof window.__FG_GAME__ !== 'undefined');
await page.waitForTimeout(1200);
const canvas = await page.locator('canvas').boundingBox();
const toScreen = (x, y) => [canvas.x + (x / 1280) * canvas.width, canvas.y + (y / 720) * canvas.height];
await page.mouse.click(...toScreen(640, 446));
await page.waitForTimeout(1600);
await page.evaluate(() => { window.__FG_GAME__.scene.getScene('Game').run.elapsedMs = 179_990; });
await page.waitForTimeout(1000);
await page.screenshot({ path: 'artifacts/v2-result-won.png' });
rec('180 秒立即結算（won）', await page.evaluate(() => window.__FG_GAME__.scene.getScene('Game').run.phase === 'won'));
await page.mouse.click(...toScreen(640, 450));
await page.waitForTimeout(700);
rec('點擊「登錄排行榜」開啟面板', await page.locator('#lb-nickname').count() === 1);
if (await page.locator('#lb-nickname').count() === 1) {
  await page.fill('#lb-nickname', '  食安小林  ');
  const hint = await page.locator('.lb-hint').first().innerText();
  rec('暱稱去首尾空白並預覽', hint.includes('食安小林'), hint);
  await page.screenshot({ path: 'artifacts/v2-submit-form.png' });
  await page.getByRole('button', { name: '登錄成績' }).click();
  await page.waitForTimeout(1000);
  const rank = await page.locator('.lb-rank').innerText().catch(() => '');
  rec('顯示本次名次（模擬）', /第 \d+ 名|未進前 100 名/.test(rank), rank);
  await page.screenshot({ path: 'artifacts/v2-submit-done.png' });
  await page.getByRole('button', { name: '回首頁' }).click();
  await page.waitForTimeout(900);
  rec('回首頁回到選單', await page.evaluate(() => window.__FG_GAME__.scene.getScenes(true).some((s) => s.scene.key === 'Menu')));
}
console.log(log.join('\n'));
await page.close();
await browser.close();
process.exit(0);
