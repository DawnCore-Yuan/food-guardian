import { chromium } from 'playwright-core';
const B = process.env.CDP ?? 'http://foodsky-test:9222';
const browser = await chromium.connectOverCDP(B, { timeout: 10000 });
const ctx = browser.contexts()[0] ?? await browser.newContext();
const page = await ctx.newPage();
const logs = [];
page.on('console', (m) => logs.push(m.type() + ': ' + m.text().slice(0, 150)));
page.on('requestfailed', (q) => logs.push('REQFAIL ' + q.url() + ' ' + (q.failure()?.errorText ?? '')));
const url = process.env.URL ?? 'http://openclaw-gateway:5181/';
const resp = await page.goto(url, { waitUntil: 'networkidle', timeout: 20000 });
await page.waitForTimeout(1200);
const assets = await page.evaluate(() => Array.from(document.images).map((i) => ({ src: i.currentSrc || i.src, w: i.naturalWidth })));
const canvas = await page.locator('canvas').count();
console.log(JSON.stringify({ status: resp?.status(), canvas, assets, logs }, null, 1));
await page.close();
await browser.close();
