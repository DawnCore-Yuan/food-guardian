import { chromium } from 'playwright-core';
const browser = await chromium.connectOverCDP('http://foodsky-test:9222');
const ctx = browser.contexts()[0] ?? await browser.newContext();
const page = await ctx.newPage();
await page.setViewportSize({ width: 1200, height: 675 });
await page.goto('http://openclaw-gateway:5181/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
const s0 = await page.evaluate(() => ({ hook: typeof window.__FG_GAME__, scripts: Array.from(document.scripts).map((s) => s.src) }));
console.log(JSON.stringify(s0));
const box = await page.locator('canvas').boundingBox();
await page.mouse.click(box.x + box.width * 0.5, box.y + box.height * 0.62);
await page.waitForTimeout(2000);
const s1 = await page.evaluate(() => {
  const g = window.__FG_GAME__;
  if (!g) return { hook: 'none' };
  return { hook: 'ok', scenes: g.scene.scenes.map((x) => [x.scene.key, x.scene.isActive()]) };
});
console.log(JSON.stringify(s1));
await page.screenshot({ path: 'artifacts/dbg-after-start.png' });
await page.close();
await browser.close();
